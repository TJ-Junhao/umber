"""Generate the combining-mark table used by umber-core's text run splitting.

Run from the repository root:

    python3 scripts/unicode/gen_marks.py

The table lists every code point whose Unicode General Category is Mn (nonspacing mark) or Me
(enclosing mark), as merged inclusive ranges. It is computed with the standard library's
``unicodedata`` module, so the Unicode version is that of the Python interpreter running the
script; the version is recorded in the generated file. Pass ``--check`` to verify that the
committed file is up to date instead of writing it.
"""

from __future__ import annotations

import sys
import unicodedata
from pathlib import Path

OUTPUT = Path(__file__).resolve().parents[2] / "crates" / "umber-core" / "src" / "text" / "marks.rs"
CATEGORIES = {"Mn", "Me"}


def mark_ranges() -> list[tuple[int, int]]:
    """Return the merged inclusive ranges of all Mn and Me code points."""
    ranges: list[tuple[int, int]] = []
    for cp in range(sys.maxunicode + 1):
        if unicodedata.category(chr(cp)) not in CATEGORIES:
            continue
        if ranges and ranges[-1][1] + 1 == cp:
            ranges[-1] = (ranges[-1][0], cp)
        else:
            ranges.append((cp, cp))
    return ranges


def render(ranges: list[tuple[int, int]]) -> str:
    """Render the Rust source of the table."""
    lines = [
        "//! General Category Mn and Me code points, generated by `scripts/unicode/gen_marks.py`.",
        "//!",
        f"//! Unicode version: {unicodedata.unidata_version}. Do not edit by hand.",
        "",
        "/// Sorted, merged, inclusive ranges of nonspacing (Mn) and enclosing (Me) marks.",
        "#[rustfmt::skip]",
        "pub(super) const MARKS: &[(u32, u32)] = &[",
    ]
    lines += [f"    (0x{lo:04X}, 0x{hi:04X})," for lo, hi in ranges]
    lines += ["];", ""]
    return "\n".join(lines)


def main() -> int:
    """Write the table, or with ``--check`` compare it with the committed file."""
    source = render(mark_ranges())
    if "--check" in sys.argv[1:]:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != source:
            print(f"{OUTPUT} is out of date", file=sys.stderr)
            return 1
        print(f"{OUTPUT} is up to date")
        return 0
    OUTPUT.write_text(source, encoding="utf-8")
    print(f"wrote {OUTPUT} (Unicode {unicodedata.unidata_version})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
